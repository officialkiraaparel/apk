function buildStagesWithStatus(completedUpToId: string, currentId: string, customNotes?: string): ProductionStageProgress[] {
  const stageList = [...INITIAL_PRODUCTION_STAGES];
  const targetIndex = stageList.findIndex(s => s.id === currentId);
  
  return stageList.map((st, idx) => {
    let status: 'pending' | 'in_progress' | 'completed' = 'pending';
    let startedAt: string | undefined = undefined;
    let completedAt: string | undefined = undefined;
    
    if (idx < targetIndex) {
      status = 'completed';
      startedAt = '2026-08-20T08:00:00Z';
      completedAt = '2026-08-23T16:00:00Z';
    } else if (idx === targetIndex) {
      status = 'in_progress';
      startedAt = '2026-08-24T09:00:00Z';
    }

    return {
      id: st.id,
      name: st.name,
      percentage: st.percentage,
      status,
      startedAt,
      completedAt,
      updatedBy: 'Pak Joko (Produksi)',
      notes: idx === targetIndex ? (customNotes || 'Sedang dikerjakan oleh tim workshop') : undefined,
    };
  });
}

